export const EXPLANATION_BY_KEY: Record<string, Explanation> = Object.fromEntries(
  EDA_EXPLANATIONS.map((e) => [e.key, e])
);

export function resolveExplanation(eduKey: string | null | undefined): Explanation | undefined {
  if (!eduKey) return undefined;
  if (EXPLANATION_BY_KEY[eduKey]) return EXPLANATION_BY_KEY[eduKey];
  // Fuzzy: table.eda.overview ↔ table.EDA.T.OVERVIEW style
  const lower = eduKey.toLowerCase();
  if (EXPLANATION_BY_KEY[lower]) return EXPLANATION_BY_KEY[lower];
  const compact = lower.replace(/[^a-z0-9.]+/g, ".");
  for (const [k, v] of Object.entries(EXPLANATION_BY_KEY)) {
    if (compact.includes(k.replace("table.eda.", "").replace("plot.eda.p.", "")) || k.includes(compact)) {
      return v;
    }
  }
  // Prefix match for plot.EDA.P.HIST.Age → univariate histogram entry
  if (lower.startsWith("plot.")) {
    return {
      key: eduKey,
      title: eduKey,
      intuitive: "Plotly artefact from the EDA engine.",
      detail: "Numbers JSON carries the computed values; PNG export is available when kaleido runs.",
      math: "\\text{see companion table}",
      assumptions: [],
      when_to_use: "EDA workbench",
      pitfalls: [],
      references: ["ARCHITECTURE §10.2"],
    };
  }
  return undefined;
}
